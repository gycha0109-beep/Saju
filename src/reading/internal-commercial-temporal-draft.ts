import type { TemporalReaderEvidence } from './temporal-reader-evidence.js';

/**
 * Reuses the existing T9 Claim -> narrative profile -> source-linked
 * research signals; does NOT invent parallel annual/monthly meanings.
 * Product-owner adoption removes the external academic gate, not the
 * exact segment, claim provenance, or signed issuance requirements.
 */
export const TEMPORAL_INTERNAL_COMMERCIAL_POLICY_V1 = Object.freeze({
  id: 'myeongha-t9-internal-commercial-interpretation-v1',
  version: '2026-11-13',
  academicApprovalRequired: false,
  interpretationOwner: 'myeongha_internal_service',
  allowedScopes: ['annual', 'monthly'] as const,
  officialIssueAuthorization: false,
});

type Signal = TemporalReaderEvidence['researchSignals'][number];

export interface TemporalInternalCommercialDraftSection {
  readonly segmentId: string;
  readonly startsAt: string;
  readonly endsAt: string;
  readonly sourceSignals: readonly Signal[];
  readonly sourceRuleRefs: readonly string[];
  readonly sourceFactRefs: readonly string[];
  readonly koreanParagraphs: readonly string[];
  readonly coverage: 'primary_claim_observed' | 'no_primary_claim';
}

export interface TemporalInternalCommercialDraftV1 {
  readonly version: 'myeongha-t9-internal-commercial-draft-v1';
  readonly policy: typeof TEMPORAL_INTERNAL_COMMERCIAL_POLICY_V1;
  readonly lifecycle: 'internal_quality_review';
  readonly scope: 'annual' | 'monthly';
  readonly snapshotId: string;
  readonly calculationHash: string;
  readonly responseBodyHash: string;
  readonly evidenceHash: string;
  readonly targetYear: number;
  readonly targetMonth?: number;
  readonly referenceDateTime: string;
  readonly sectionCoverage:
    'all_period_segments_have_primary_claim' | 'one_or_more_segments_uncovered';
  readonly sections: readonly TemporalInternalCommercialDraftSection[];
  readonly readyForInternalNarrativeQualityTest: boolean;
  readonly readyForOfficialIssue: false;
  readonly maySell: false;
}

export function buildTemporalInternalCommercialDraftV1(
  evidence: TemporalReaderEvidence,
): TemporalInternalCommercialDraftV1 {
  const sectionIds = new Set(evidence.segments.map(x => x.id));
  if (sectionIds.size !== evidence.segments.length ||
      !Number.isSafeInteger(evidence.targetYear) ||
      evidence.referenceSegmentId === null ||
      !sectionIds.has(evidence.referenceSegmentId) ||
      evidence.segments.some(x => !(x.startsAt < x.endsAt)) ||
      evidence.researchSignals.some(x =>
        !sectionIds.has(x.segmentId) || !x.claimId ||
        !x.statement.trim() || x.ruleRefs.length === 0 ||
        x.factRefs.length === 0 || x.sourceRefs.length === 0)) {
    throw new TypeError('T9 internal service copy requires original time-window and claim provenance.');
  }
  const sections = evidence.segments.map(segment => {
    const sourceSignals = evidence.researchSignals
      .filter(signal => signal.segmentId === segment.id);
    const coverage = sourceSignals.some(x => x.kind === 'primary')
      ? 'primary_claim_observed' as const : 'no_primary_claim' as const;
    return {
      segmentId: segment.id,
      startsAt: segment.startsAt,
      endsAt: segment.endsAt,
      sourceSignals,
      sourceRuleRefs: [...new Set(sourceSignals.flatMap(x => x.ruleRefs))],
      sourceFactRefs: [...new Set(sourceSignals.flatMap(x => x.factRefs))],
      // Preserve the text generated by the existing governed profile verbatim.
      koreanParagraphs: sourceSignals.map(x => x.statement),
      coverage,
    };
  });
  const complete = sections.every(x => x.coverage === 'primary_claim_observed');
  return {
    version: 'myeongha-t9-internal-commercial-draft-v1',
    policy: TEMPORAL_INTERNAL_COMMERCIAL_POLICY_V1,
    lifecycle: 'internal_quality_review',
    scope: evidence.scope,
    snapshotId: evidence.snapshotId,
    calculationHash: evidence.calculationHash,
    responseBodyHash: evidence.responseBodyHash,
    evidenceHash: evidence.evidenceHash,
    targetYear: evidence.targetYear,
    ...('targetMonth' in evidence ? { targetMonth: evidence.targetMonth } : {}),
    referenceDateTime: evidence.referenceDateTime,
    sectionCoverage: complete
      ? 'all_period_segments_have_primary_claim'
      : 'one_or_more_segments_uncovered',
    sections,
    readyForInternalNarrativeQualityTest: complete,
    readyForOfficialIssue: false,
    maySell: false,
  };
}
